#!/usr/bin/env python3
"""Wire all remaining vanilla localization keys not yet in Translations/*.ga.json."""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from collections import Counter
from pathlib import Path

_TOOLS = Path(__file__).resolve().parent
_REPO = _TOOLS.parent

if str(_TOOLS) not in sys.path:
    sys.path.insert(0, str(_TOOLS))

from count_vanilla_keys import key_prefix, load_all_keys, load_wired_keys
from discover_scope_keys import load_tables


def run(cmd: list[str]) -> None:
    print("+", " ".join(cmd), flush=True)
    subprocess.run(cmd, check=True, cwd=_REPO)


def write_remainder_scope(
    repo: Path, game_path: Path, scope_out: Path
) -> tuple[int, dict[str, int]]:
    resources = game_path / "valheim_Data" / "resources.assets"
    keys, _, _ = load_all_keys(resources)
    wired = load_wired_keys(repo)
    uncovered = sorted(set(keys) - wired)
    by_prefix = Counter(key_prefix(k) for k in uncovered)

    header = (
        f"# Final sweep: all vanilla keys not already wired ({len(uncovered)} keys).\n"
        f"# Generated by tools/run_final_sweep.py\n"
    )
    scope_out.parent.mkdir(parents=True, exist_ok=True)
    scope_out.write_text(header + "\n".join(uncovered) + "\n", encoding="utf-8")
    print(f"Wrote {len(uncovered)} keys to {scope_out}")
    return len(uncovered), dict(by_prefix.most_common())


def count_duplicate_ga_keys(trans_dir: Path) -> list[str]:
    seen: dict[str, str] = {}
    dups: list[str] = []
    for ga in sorted(trans_dir.glob("*.ga.json")):
        data = json.loads(ga.read_text(encoding="utf-8"))
        for entry in data.get("entries", []):
            key = entry["key"]
            if key in seen:
                dups.append(f"{key} ({seen[key]} + {ga.name})")
            else:
                seen[key] = ga.name
    return dups


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--game-path",
        type=Path,
        default=Path(r"A:\Steam\steamapps\common\Valheim"),
    )
    parser.add_argument("--repo", type=Path, default=_REPO)
    parser.add_argument(
        "--scope",
        type=Path,
        default=_REPO / "tools" / "scopes" / "remainder.keys.txt",
    )
    parser.add_argument(
        "--extract",
        type=Path,
        default=_REPO / "plugins" / "irish-mod" / "extracted" / "remainder.json",
    )
    parser.add_argument(
        "--irish-map",
        type=Path,
        default=_REPO / "tools" / "remainder_irish_map.json",
    )
    parser.add_argument(
        "--ga-out",
        type=Path,
        default=_REPO / "plugins" / "irish-mod" / "Translations" / "remainder.ga.json",
    )
    parser.add_argument(
        "--scope-only",
        action="store_true",
        help="Only regenerate remainder.keys.txt",
    )
    args = parser.parse_args()

    resources = args.game_path / "valheim_Data" / "resources.assets"
    keys, _, _ = load_all_keys(resources)
    wired = load_wired_keys(args.repo)
    uncovered_n = len(set(keys) - wired)
    if uncovered_n == 0:
        print("Nothing to wire — already at full coverage.")
        if args.scope_only:
            return 0
    n, prefixes = write_remainder_scope(args.repo, args.game_path, args.scope)
    if n == 0:
        return 0

    top = list(prefixes.items())[:15]
    print("Uncovered by prefix (top 15):", json.dumps(top, indent=2))
    if args.scope_only:
        return 0

    py = sys.executable
    run(
        [
            py,
            str(_TOOLS / "run_coverage_batch.py"),
            "--scope",
            str(args.scope),
            "--screen-id",
            "remainder",
            "--screen-title",
            "Remaining vanilla localization keys",
            "--extract",
            str(args.extract),
            "--irish-map",
            str(args.irish_map),
            "--ga-out",
            str(args.ga_out),
        ]
    )

    trans = args.repo / "plugins" / "irish-mod" / "Translations"
    dups = count_duplicate_ga_keys(trans)
    if dups:
        print(f"ERROR: {len(dups)} duplicate keys across *.ga.json", file=sys.stderr)
        for line in dups[:20]:
            print(f"  {line}", file=sys.stderr)
        return 1

    resources = args.game_path / "valheim_Data" / "resources.assets"
    tables = load_tables(resources)
    wired = load_wired_keys(args.repo)
    covered = len(set(tables) & wired)
    total = len(tables)
    pct = round(100.0 * covered / total, 2) if total else 0
    print(
        json.dumps(
            {
                "unique_vanilla_keys": total,
                "wired_keys": len(wired),
                "covered_in_vanilla": covered,
                "uncovered_vanilla_keys": total - covered,
                "coverage_pct": pct,
                "duplicate_keys": 0,
            },
            indent=2,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
